// A dish's or a product's name with "the" in a card line and in א5's bubble (stage 8, questions 35; worker/shuki.js theDish)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { theDish } from '../worker/shuki.js';

test('theDish: one word, a construct, an adjective that agrees, a preposition; in quotes when no rule can tell', () => {
  for (const [name, want] of [
    ['שקשוקה', 'השקשוקה'], ["קוטג'", "הקוטג'"],
    ['פשטידת תרד', 'פשטידת התרד'], ['עוגת לימון', 'עוגת הלימון'], ['עוגת גבינה', 'עוגת הגבינה'], ['קופסת טונה', 'קופסת הטונה'],
    ['מנת פסטה', 'מנת הפסטה'], ['פחית קולה', 'פחית הקולה'], ['ריבת תות', 'ריבת התות'], ['שמיכת דאמפלינג', 'שמיכת הדאמפלינג'],
    ['קציצות בקר', 'קציצות הבקר'], ['עוגיות שוקולד', 'עוגיות השוקולד'], ['פרוסות עגבניות', 'פרוסות העגבניות'], ['מרק עדשים', 'מרק העדשים'],
    ['חזה העוף', 'חזה העוף'], ['חזה עוף', 'חזה העוף'], ['חזה הודו', 'חזה ההודו'], ['גבינת הלומי', 'גבינת ההלומי'], ['חזה עוף בתנור', 'חזה העוף בתנור'],
    ['גבינה צהובה', 'הגבינה הצהובה'], ['כרובית צלויה', 'הכרובית הצלויה'], ['עגבניות ממולאות', 'העגבניות הממולאות'], ['שמנת מתוקה', 'השמנת המתוקה'],
    ['סלמון בתנור', 'הסלמון בתנור'], ['פרגית בתנור', 'הפרגית בתנור'], ['שמנת לבישול', 'השמנת לבישול'], ['פסטה ברוטב עגבניות', 'הפסטה ברוטב עגבניות'],
    ['סלט יווני', '"סלט יווני"'], ['אורז לבן', '"אורז לבן"'], ['שניצל הודו', '"שניצל הודו"'], ['חלב 3%', '"חלב 3%"'],
  ]) assert.equal(theDish(name), want, name);
});
