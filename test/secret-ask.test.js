// An explicit ask for a secret (the owner 03/10, questions 40 and 44): what the server marks private by itself.
import test from 'node:test';
import assert from 'node:assert/strict';
import { isSecret } from '../worker/shuki.js';

const HOUSE = ['אבי', 'מיכל', 'יואבי'];
const is = (t) => isSecret(t, HOUSE);

test('asks for a secret', () => {
  for (const t of ['אל תגיד לאבי, אני בהריון', 'אל תספרי לאמא', 'שלא תדע.', 'שלא ידעו', 'זה נשאר בינינו', 'זה סוד', 'מה הסוד',
    // 44ד
    'אל תגלה לאבא', 'אל תגלי למיכל', 'אל תגידו לסבתא', 'אל תספרו לילדים', 'אל תגיד את זה לאבי', 'בסוד, תוסיף עוגה', 'זה סודי',
    'בלי שהיא תדע', 'בלי שאבא ידע', 'אבא לא צריך לדעת', 'אבא לא צריך לדעת את זה', 'ושאמא לא תדע',
    // 45: anywhere in the sentence; and these stay caught (the safe side)
    'לא צריך לדעת על זה', 'הם לא צריכים לדעת שקניתי', 'חבל שאבא לא ידע', 'אל תגיד לא לעוגה', 'אל תגלה לו את הסוף', 'היא לא צריכה לדעת.', 'שאבא לא ידע', 'שמיכל לא תדע']) assert.ok(is(t), t);
});

test('not a secret', () => {
  for (const t of ['תוסיף סודה', 'סודות', 'אני לא יודע', 'הוא לא ידע שאכלתי', 'היא לא תדע מה לעשות', 'תגיד לאבי שאני מאחר',
    // 44ג
    'אל תגיד לי מה לעשות', 'אל תספר לנו בדיחות', 'אל תגידי לי', 'אל תספרו לנו',
    // the reviewer's false positives (03/10)
    'אמרתי שהילד לא ידע שנגמר החלב', 'כנראה שהוא לא ידע שאין חלב', 'חבל שהשכן לא ידע', 'קניתי בלי שבדקתי, מי ידע',
    'בלי שיש לי מידע על המוצר', 'תשמור את המתכון הסודי של סבתא', 'המרכיב הסודי הוא קינמון']) assert.ok(!is(t), t);
});
